/// Returns the rows of the glyph of `c`: a space and any character the font does not know are
/// blank.
pub fn glyph(c: char) -> [u8; HEIGHT] {
    GLYPHS
        .iter()
        .find(|(known, _)| *known == c)
        .map_or([0; HEIGHT], |(_, rows)| *rows)
}
